CREATE VIEW public.v_riesgo_estudiantes AS
 SELECT e.id AS id_estudiante,
    (((p.primer_nombre)::text || ' '::text) || (p.primer_apellido)::text) AS nombre_completo,
    COALESCE(avg(n.valor), (0)::numeric) AS promedio_notas,
    COALESCE(max(a.porcentaje_asistencia), (0)::numeric) AS asistencia,
    ds.nivel_socioeconomico,
    ( SELECT count(*) AS count
           FROM public.core_cuota c
          WHERE ((c.id_estudiante = e.id) AND ((c.estado_pago)::text = 'vencido'::text))) AS cuotas_vencidas
   FROM ((((public.estudiante e
     JOIN public.persona p ON ((e.id_persona = p.id)))
     LEFT JOIN public.core_nota n ON ((e.id = n.id_estudiante)))
     LEFT JOIN public.core_asistencia a ON ((e.id = a.id_estudiante)))
     LEFT JOIN public.core_datossocioeconomicos ds ON ((e.id = ds.id_estudiante)))
  GROUP BY e.id, p.primer_nombre, p.primer_apellido, ds.nivel_socioeconomico;


